//go:build ignore

// gen-notices writes THIRD_PARTY_NOTICES.md for the modules the capm CLI can
// link: every module that provides a package in `go list -deps ./...` of the
// cli module (non-test), in the same workspace mode the release build uses.
// It reads each module's LICENSE/COPYING/NOTICE files from the module cache
// and classifies them by their text. A module whose licence it cannot
// classify is listed as UNKNOWN (never guessed), with the reason.
//
//	cd cli && go run ../scripts/gen-notices.go > THIRD_PARTY_NOTICES.md
//
// Invoked by scripts/gen-notices.sh. Output is deterministic: no dates, no
// local paths.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type module struct {
	Path, Version string
	files         []licFile // licence-like files found at the module root
	types         []string  // detected SPDX-ish ids, one per licence file
	problem       string    // why it is UNKNOWN, if it is
}

type licFile struct {
	name string
	text string
}

func main() {
	mods := listModules()
	var unknown []*module
	for _, m := range mods {
		classify(m)
		if m.problem != "" {
			unknown = append(unknown, m)
		}
	}
	hashes := map[string]string{}
	for _, f := range []string{"go.mod", "go.sum", "../go.work"} {
		hashes[filepath.Base(f)] = fileHash(f)
	}

	w := os.Stdout
	fmt.Fprintf(w, "# Third-party notices\n\n")
	fmt.Fprintf(w, "The capm CLI is built from this repository's code plus the Go modules below.\n")
	fmt.Fprintf(w, "This file is generated by `scripts/gen-notices.sh`; do not edit it by hand.\n")
	fmt.Fprintf(w, "It covers every module that provides a package in `go list -deps ./...` of\n")
	fmt.Fprintf(w, "the `cli` module (a superset of what a given release links, because the linker\n")
	fmt.Fprintf(w, "drops unreferenced packages), resolved as the release build resolves them\n")
	fmt.Fprintf(w, "(Go workspace mode). Licence types are detected from the LICENSE, COPYING and\n")
	fmt.Fprintf(w, "NOTICE files in the module cache by matching their text; anything not\n")
	fmt.Fprintf(w, "recognised is listed as UNKNOWN rather than guessed.\n\n")
	fmt.Fprintf(w, "Inputs (SHA-256), checked by a test so this file cannot silently go stale:\n\n")
	fmt.Fprintf(w, "- cli/go.mod: %s\n- cli/go.sum: %s\n- go.work: %s\n\n", hashes["go.mod"], hashes["go.sum"], hashes["go.work"])

	counts := map[string]int{}
	for _, m := range mods {
		counts[typeLabel(m)]++
	}
	var labels []string
	for l := range counts {
		labels = append(labels, l)
	}
	sort.Strings(labels)
	fmt.Fprintf(w, "## Summary\n\n%d modules.", len(mods))
	for _, l := range labels {
		fmt.Fprintf(w, " %s: %d.", l, counts[l])
	}
	fmt.Fprintf(w, "\n\n")
	if len(unknown) == 0 {
		fmt.Fprintf(w, "No module has an unrecognised licence.\n\n")
	} else {
		fmt.Fprintf(w, "**Modules with an unrecognised licence (need a human):**\n\n")
		for _, m := range unknown {
			fmt.Fprintf(w, "- `%s` %s: %s\n", m.Path, m.Version, m.problem)
		}
		fmt.Fprintf(w, "\n")
	}

	fmt.Fprintf(w, "## Modules\n\n| Module | Version | Licence | Files |\n|---|---|---|---|\n")
	for _, m := range mods {
		var names []string
		for _, f := range m.files {
			names = append(names, f.name)
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s |\n", m.Path, m.Version, typeLabel(m), strings.Join(names, ", "))
	}

	// Licence texts, each distinct text once, with the modules it applies to.
	type group struct {
		text    string
		modules []string
		names   map[string]bool
	}
	groups := map[string]*group{}
	var order []string
	for _, m := range mods {
		for _, f := range m.files {
			sum := sha256.Sum256([]byte(normalise(f.text)))
			k := hex.EncodeToString(sum[:])
			g := groups[k]
			if g == nil {
				g = &group{text: f.text, names: map[string]bool{}}
				groups[k] = g
				order = append(order, k)
			}
			g.modules = append(g.modules, m.Path+" "+m.Version)
			g.names[f.name] = true
		}
	}
	sort.Slice(order, func(i, j int) bool { return groups[order[i]].modules[0] < groups[order[j]].modules[0] })
	fmt.Fprintf(w, "\n## Licence and notice texts\n\nEach distinct text appears once, followed by the modules whose licence files contain it.\n")
	for _, k := range order {
		g := groups[k]
		fmt.Fprintf(w, "\n---\n\n**Applies to:** ")
		sort.Strings(g.modules)
		for i, s := range g.modules {
			if i > 0 {
				fmt.Fprintf(w, ", ")
			}
			fmt.Fprintf(w, "`%s`", s)
		}
		fmt.Fprintf(w, "\n\n````text\n%s\n````\n", strings.TrimRight(g.text, "\n"))
	}
}

func fileHash(p string) string {
	b, err := os.ReadFile(p)
	if err != nil {
		fatal(err)
	}
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}

func normalise(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func typeLabel(m *module) string {
	if m.problem != "" {
		return "UNKNOWN"
	}
	seen := map[string]bool{}
	var out []string
	for _, t := range m.types {
		if !seen[t] {
			seen[t] = true
			out = append(out, t)
		}
	}
	return strings.Join(out, " + ")
}

func listModules() []*module {
	cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}\t{{.Main}}{{end}}", "./...")
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		fatal(fmt.Errorf("go list: %w", err))
	}
	seen := map[string]bool{}
	var mods []*module
	dirs := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		f := strings.Split(line, "\t")
		if len(f) != 4 || f[3] == "true" || seen[f[0]] {
			continue
		}
		// This repository's own modules (cli is main; manifest is a local replace).
		if strings.HasPrefix(f[0], "github.com/MasonD-007/capm/") {
			continue
		}
		seen[f[0]] = true
		mods = append(mods, &module{Path: f[0], Version: f[1]})
		dirs[f[0]] = f[2]
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	for _, m := range mods {
		m.files = findFiles(dirs[m.Path])
	}
	return mods
}

// findFiles returns the licence-like files at the root of a module directory.
func findFiles(dir string) []licFile {
	ents, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	var out []licFile
	for _, e := range ents {
		if e.IsDir() || strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		n := strings.ToUpper(e.Name())
		if strings.HasPrefix(n, "LICENSE") || strings.HasPrefix(n, "LICENCE") || strings.HasPrefix(n, "COPYING") || strings.HasPrefix(n, "NOTICE") || strings.HasPrefix(n, "UNLICENSE") {
			b, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err == nil && len(b) < 200<<10 {
				out = append(out, licFile{name: e.Name(), text: strings.ReplaceAll(string(b), "\r\n", "\n")})
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}

func classify(m *module) {
	if len(m.files) == 0 {
		m.problem = "no LICENSE, COPYING or NOTICE file at the module root"
		return
	}
	for _, f := range m.files {
		if strings.HasPrefix(strings.ToUpper(f.name), "NOTICE") {
			continue // a NOTICE accompanies a licence; it is not one
		}
		t := detect(f.text)
		if t == "" {
			m.problem = fmt.Sprintf("%s did not match any known licence text", f.name)
			return
		}
		m.types = append(m.types, t)
	}
	if len(m.types) == 0 {
		m.problem = "only a NOTICE file; no licence text"
	}
}

// detect classifies a licence text by distinctive phrases. It recognises only
// the licences the dependency set actually uses; anything else is "".
func detect(text string) string {
	t := strings.ToLower(normalise(text))
	has := func(s string) bool { return strings.Contains(t, strings.ToLower(s)) }
	// A file may carry more than one licence (gopkg.in/yaml.v3 is MIT plus an
	// Apache-2.0 header), so every match is reported.
	var found []string
	switch {
	case has("apache license") && has("version 2.0, january 2004"):
		found = append(found, "Apache-2.0")
	case has("licensed under the apache license, version 2.0") && has("without warranties or conditions of any kind"):
		// The short boilerplate header, without the full licence text.
		found = append(found, "Apache-2.0 (header only)")
	}
	if has("attribution-sharealike 4.0 international") {
		found = append(found, "CC-BY-SA-4.0")
	}
	if has("mozilla public license") && has("version 2.0") {
		found = append(found, "MPL-2.0")
	}
	if has("permission is hereby granted, free of charge, to any person obtaining a copy") {
		found = append(found, "MIT")
	}
	if has("permission to use, copy, modify, and/or distribute this software for any purpose with or without fee") {
		found = append(found, "ISC")
	}
	if has("redistribution and use in source and binary forms, with or without modification") {
		if has("neither the name") {
			found = append(found, "BSD-3-Clause")
		} else {
			found = append(found, "BSD-2-Clause")
		}
	}
	if has("this is free and unencumbered software released into the public domain") {
		found = append(found, "Unlicense")
	}
	return strings.Join(found, " + ")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-notices:", err)
	os.Exit(1)
}
