package main

import (
	"fmt"
	"strings"
)

// Generators for `capm completion bash|zsh|fish`, all driven by commandTable.
// The scripts hold the static words (commands, flags, enum values) inline and
// call `capm __complete bundles <prefix>` for the one dynamic thing, bundle
// references; directories and paths are left to each shell's own completion.

// completionScript returns the script for shell, or false for an unknown shell.
func completionScript(shell string) (string, bool) {
	switch shell {
	case "bash":
		return genBash(), true
	case "zsh":
		return genZsh(), true
	case "fish":
		return genFish(), true
	}
	return "", false
}

func words(ss []string) string { return strings.Join(ss, " ") }

// flagWords lists the long flags of a command, for "complete a word that starts with -".
func flagWords(fs []flagSpec) []string {
	var out []string
	for _, f := range fs {
		out = append(out, "--"+f.Name)
	}
	return out
}

// topNames are the commands completed at the first position (not hidden ones).
func topNames() []string {
	var out []string
	for _, c := range commandTable {
		if !c.Hidden {
			out = append(out, c.Name)
		}
	}
	return out
}

func subNames(c cmdSpec) []string {
	var out []string
	for _, s := range c.Subs {
		out = append(out, s.Name)
	}
	return out
}

// flagPattern is a shell case pattern matching a flag in its -x and --x forms
// (the Go flag package accepts both).
func flagPattern(name string, short string) string {
	p := "--" + name + "|-" + name
	if short != "" {
		p += "|-" + short
	}
	return p
}

type writer struct{ b strings.Builder }

func (w *writer) f(indent int, format string, a ...any) {
	w.b.WriteString(strings.Repeat("  ", indent))
	fmt.Fprintf(&w.b, format, a...)
	w.b.WriteByte('\n')
}

func (w *writer) raw(s string) { w.b.WriteString(s) }

// --- bash --------------------------------------------------------------------

const bashHead = `# bash completion for capm. Generated by "capm completion bash"; do not edit.
#
#   source <(capm completion bash)                      # this shell only
#   capm completion bash > ~/.local/share/bash-completion/completions/capm
#
# Works with bash 3.2 and later; it needs only "complete -F", not the
# bash-completion package. Bundle references come from "capm __complete
# bundles", which asks the registry for at most one second and never fails.

_capm_words() {
  COMPREPLY=( $(compgen -W "$1" -- "$cur") )
}

_capm_bundles() {
  COMPREPLY=( $("${COMP_WORDS[0]}" __complete bundles "$cur" 2>/dev/null) )
}

# _capm_files -d|-f: bash 4+ completes (and quotes) names itself; on bash 3.2,
# which has no compopt, COMPREPLY stays empty and the "-o default" given to
# complete below makes readline complete file names.
_capm_files() {
  if type compopt >/dev/null 2>&1; then
    local IFS=$'\n'
    compopt -o filenames 2>/dev/null
    COMPREPLY=( $(compgen "$1" -- "$cur") )
  fi
}

_capm_ref_or_dir() {
  case "$cur" in
    ./*|../*|/*|"~"*|.|..) _capm_files -d; return 0 ;;
  esac
  _capm_bundles
  if [ "${#COMPREPLY[@]}" -eq 0 ]; then _capm_files -d; fi
}

_capm() {
  local cur prev
  COMPREPLY=()
  cur="${COMP_WORDS[COMP_CWORD]}"
  prev=""
  if [ "$COMP_CWORD" -ge 1 ]; then prev="${COMP_WORDS[COMP_CWORD-1]}"; fi
  # readline splits --flag=value into three words: --flag, =, value.
  if [ "$cur" = "=" ]; then cur=""; fi
  if [ "$prev" = "=" ] && [ "$COMP_CWORD" -ge 2 ]; then prev="${COMP_WORDS[COMP_CWORD-2]}"; fi

`

func genBash() string {
	var w writer
	w.raw(bashHead)
	w.f(1, `if [ "$COMP_CWORD" -le 1 ]; then _capm_words "%s"; return 0; fi`, words(topNames()))
	w.f(1, `case "${COMP_WORDS[1]}" in`)
	for _, c := range commandTable {
		w.f(2, "%s)", c.Name)
		bashSpec(&w, c, 1, 3)
		w.f(3, ";;")
	}
	w.f(1, "esac")
	w.f(1, "return 0")
	w.raw("}\n\n")
	w.raw(`if type compopt >/dev/null 2>&1; then
  complete -F _capm capm
else
  complete -o default -F _capm capm
fi
`)
	return w.b.String()
}

// bashSpec emits the body for spec, whose own word is COMP_WORDS[d].
func bashSpec(w *writer, c cmdSpec, d, ind int) {
	if len(c.Subs) > 0 {
		w.f(ind, `if [ "$COMP_CWORD" -eq %d ]; then _capm_words "%s"; return 0; fi`, d+1, words(subNames(c)))
		w.f(ind, `case "${COMP_WORDS[%d]}" in`, d+1)
		for _, s := range c.Subs {
			w.f(ind+1, "%s)", s.Name)
			bashSpec(w, s, d+1, ind+2)
			w.f(ind+2, ";;")
		}
		w.f(ind, "esac")
		w.f(ind, "return 0")
		return
	}
	var valued []flagSpec
	for _, f := range c.Flags {
		if f.Value != valNone {
			valued = append(valued, f)
		}
	}
	if len(valued) > 0 {
		w.f(ind, `case "$prev" in`)
		for _, f := range valued {
			switch f.Value {
			case valEnum:
				w.f(ind+1, `%s) _capm_words "%s"; return 0 ;;`, flagPattern(f.Name, f.Short), words(f.Enum))
			case valDir:
				w.f(ind+1, `%s) _capm_files -d; return 0 ;;`, flagPattern(f.Name, f.Short))
			case valFile:
				w.f(ind+1, `%s) _capm_files -f; return 0 ;;`, flagPattern(f.Name, f.Short))
			default:
				w.f(ind+1, `%s) return 0 ;;`, flagPattern(f.Name, f.Short))
			}
		}
		w.f(ind, "esac")
	}
	if len(c.Flags) > 0 {
		w.f(ind, `case "$cur" in`)
		w.f(ind+1, `-*) _capm_words "%s"; return 0 ;;`, words(flagWords(c.Flags)))
		w.f(ind, "esac")
	}
	switch c.Pos {
	case posBundle:
		w.f(ind, "_capm_bundles")
	case posDir:
		w.f(ind, "_capm_files -d")
	case posDirOrBundle:
		w.f(ind, "_capm_ref_or_dir")
	case posShell:
		w.f(ind, `if [ "$COMP_CWORD" -eq %d ]; then _capm_words "%s"; fi`, d+1, words(completionShells))
	default:
		w.f(ind, "# no positional argument is completed")
	}
	w.f(ind, "return 0")
}

// --- zsh ---------------------------------------------------------------------

const zshHead = `#compdef capm
# zsh completion for capm. Generated by "capm completion zsh"; do not edit.
#
#   source <(capm completion zsh)             # after compinit; this shell only
#   capm completion zsh > "${fpath[1]}/_capm"  # or put it on your fpath
#
# Bundle references come from "capm __complete bundles", which asks the
# registry for at most one second and never fails.

_capm_bundles() {
  local -a refs
  refs=(${(f)"$("${words[1]}" __complete bundles "$PREFIX" 2>/dev/null)"})
  if (( ${#refs} )); then compadd -- $refs; fi
}

_capm() {
  local cur="${words[CURRENT]}" prev="${words[CURRENT-1]}" flag=""
  local -a vals
  # --flag=value arrives as one word: complete the value after the "=".
  if [[ $cur == -*=* ]]; then
    flag="${cur%%=*}"
    compset -P '*='
  elif [[ $prev == -* ]]; then
    flag="$prev"
  fi

`

func zshQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

func zshDescribe(w *writer, ind int, name string, specs []cmdSpec, hidden bool) {
	w.f(ind, "local -a %s", name)
	w.f(ind, "%s=(", name)
	for _, s := range specs {
		if s.Hidden && !hidden {
			continue
		}
		w.f(ind+1, "%s", zshQuote(strings.ReplaceAll(s.Name, ":", `\:`)+":"+s.Desc))
	}
	w.f(ind, ")")
	w.f(ind, "_describe 'command' %s", name)
}

func genZsh() string {
	var w writer
	w.raw(zshHead)
	w.f(1, "if (( CURRENT == 2 )); then")
	zshDescribe(&w, 2, "cmds", commandTable, false)
	w.f(2, "return 0")
	w.f(1, "fi")
	w.f(1, "case ${words[2]} in")
	for _, c := range commandTable {
		w.f(2, "%s)", c.Name)
		zshSpec(&w, c, 2, 3)
		w.f(3, ";;")
	}
	w.f(1, "esac")
	w.f(1, "return 0")
	w.raw("}\n\n")
	w.raw(`if [ "$funcstack[1]" = "_capm" ]; then
  _capm "$@"
else
  compdef _capm capm
fi
`)
	return w.b.String()
}

// zshSpec emits the body for spec, whose own word is words[d].
func zshSpec(w *writer, c cmdSpec, d, ind int) {
	if len(c.Subs) > 0 {
		w.f(ind, "if (( CURRENT == %d )); then", d+1)
		zshDescribe(w, ind+1, "subs", c.Subs, true)
		w.f(ind+1, "return 0")
		w.f(ind, "fi")
		w.f(ind, "case ${words[%d]} in", d+1)
		for _, s := range c.Subs {
			w.f(ind+1, "%s)", s.Name)
			zshSpec(w, s, d+1, ind+2)
			w.f(ind+2, ";;")
		}
		w.f(ind, "esac")
		w.f(ind, "return 0")
		return
	}
	var valued []flagSpec
	for _, f := range c.Flags {
		if f.Value != valNone {
			valued = append(valued, f)
		}
	}
	if len(valued) > 0 {
		w.f(ind, "case $flag in")
		for _, f := range valued {
			switch f.Value {
			case valEnum:
				w.f(ind+1, "%s) vals=(%s); compadd -- $vals; return 0 ;;", flagPattern(f.Name, f.Short), words(f.Enum))
			case valDir:
				w.f(ind+1, "%s) _files -/; return 0 ;;", flagPattern(f.Name, f.Short))
			case valFile:
				w.f(ind+1, "%s) _files; return 0 ;;", flagPattern(f.Name, f.Short))
			default:
				w.f(ind+1, "%s) return 0 ;;", flagPattern(f.Name, f.Short))
			}
		}
		w.f(ind, "esac")
	}
	if len(c.Flags) > 0 {
		w.f(ind, "if [[ $PREFIX == -* ]]; then vals=(%s); compadd -- $vals; return 0; fi", words(flagWords(c.Flags)))
	}
	switch c.Pos {
	case posBundle:
		w.f(ind, "_capm_bundles")
	case posDir:
		w.f(ind, "_files -/")
	case posDirOrBundle:
		w.f(ind, `case $PREFIX in ./*|../*|/*|\~*|.|..) _files -/; return 0 ;; esac`)
		w.f(ind, "_capm_bundles")
		w.f(ind, "_files -/")
	case posShell:
		w.f(ind, "if (( CURRENT == %d )); then vals=(%s); compadd -- $vals; fi", d+1, words(completionShells))
	default:
		w.f(ind, "# no positional argument is completed")
	}
	w.f(ind, "return 0")
}

// --- fish --------------------------------------------------------------------

const fishHead = `# fish completion for capm. Generated by "capm completion fish"; do not edit.
#
#   capm completion fish | source                                  # this shell only
#   capm completion fish > ~/.config/fish/completions/capm.fish
#
# Bundle references come from "capm __complete bundles", which asks the
# registry for at most one second and never fails.

function __capm_argc
    count (commandline -opc)
end

# __capm_at WORD...: the words after capm that are already typed (the word
# under the cursor excluded) start with WORD...
function __capm_at
    set -l t (commandline -opc)
    set -l n (count $argv)
    test (count $t) -gt $n; or return 1
    for i in (seq $n)
        test "$t[(math $i + 1)]" = "$argv[$i]"; or return 1
    end
    return 0
end

function __capm_bundles
    set -l t (commandline -opc)
    $t[1] __complete bundles (commandline -ct) 2>/dev/null
end

complete -c capm -f

`

func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

func genFish() string {
	var w writer
	w.raw(fishHead)
	for _, c := range commandTable {
		if c.Hidden {
			continue
		}
		w.f(0, "complete -c capm -n 'test (__capm_argc) -eq 1' -a %s -d %s", fishQuote(c.Name), fishQuote(c.Desc))
	}
	for _, c := range commandTable {
		fishSpec(&w, c, []string{c.Name})
	}
	return w.b.String()
}

func fishSpec(w *writer, c cmdSpec, path []string) {
	at := "__capm_at " + strings.Join(path, " ")
	if len(c.Subs) > 0 {
		w.raw("\n")
		for _, s := range c.Subs {
			w.f(0, "complete -c capm -n '%s; and test (__capm_argc) -eq %d' -a %s -d %s", at, len(path)+1, fishQuote(s.Name), fishQuote(s.Desc))
		}
		for _, s := range c.Subs {
			fishSpec(w, s, append(append([]string{}, path...), s.Name))
		}
		return
	}
	w.raw("\n")
	w.f(0, "# capm %s", strings.Join(path, " "))
	for _, f := range c.Flags {
		line := fmt.Sprintf("complete -c capm -n '%s' -l %s", at, f.Name)
		if f.Short != "" {
			line += " -s " + f.Short
		}
		switch f.Value {
		case valEnum:
			line += " -x -a " + fishQuote(words(f.Enum))
		case valDir:
			line += " -r -a '(__fish_complete_directories)'"
		case valFile:
			line += " -r -F"
		case valFree:
			line += " -x"
		}
		w.f(0, "%s", line)
	}
	base := fmt.Sprintf("complete -c capm -n '%s", at)
	switch c.Pos {
	case posBundle:
		w.f(0, "%s' -a '(__capm_bundles)'", base)
	case posDir:
		w.f(0, "%s' -a '(__fish_complete_directories)'", base)
	case posDirOrBundle:
		w.f(0, "%s' -a '(__capm_bundles)'", base)
		w.f(0, "%s' -a '(__fish_complete_directories)'", base)
	case posShell:
		w.f(0, "%s; and test (__capm_argc) -eq 2' -a %s", base, fishQuote(words(completionShells)))
	}
}
